def fetch_sp500_tickers() -> pd.DataFrame:
    df = pd.DataFrame(SP500_TICKERS, columns=["ticker", "name", "sector"])
    df["industry"] = ""
    return df


def load_universe(tickers_df: pd.DataFrame):
    session = get_session()
    added = 0
    skipped = 0
    for _, row in tqdm(tickers_df.iterrows(), total=len(tickers_df), desc="Loading universe"):
        exists = session.query(Universe).filter_by(ticker=row["ticker"]).first()
        if exists:
            skipped += 1
            continue
        session.add(Universe(
            ticker=row["ticker"],
            name=row["name"],
            sector=row["sector"],
            industry=row["industry"],
            is_active=1,
        ))
        added += 1
    session.commit()
    session.close()
    print(f"Universe loaded: {added} added, {skipped} skipped.")


def get_universe_tickers() -> list:
    session = get_session()
    tickers = [row.ticker for row in session.query(Universe).filter_by(is_active=1).all()]
    session.close()
    return tickers


